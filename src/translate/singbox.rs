/// Tag of the selector group a multi-node config routes through.
const SELECTOR_TAG: &str = "select";

/// Render several nodes as one sing-box config.
///
/// Not a concatenation of single-node configs: sing-box takes one outbound
/// list and one `route.final`, so a multi-node export needs a `selector`
/// outbound for the user to switch between nodes in their client.
///
/// # Errors
/// [`EmitError::Refused`] when the list is empty, when the target does not run
/// sing-box, or when every node is rejected by [`gate`].
pub fn emit_nodes(nodes: &[Node], target: ClientTarget, enhanced: bool) -> Result<Emitted, EmitError> {
    if target.core() != Core::SingBox {
        return Err(EmitError::Refused(vec![format!(
            "{} runs {}, not sing-box, so a sing-box JSON config would not be read by it",
            target.name(),
            target.core().name()
        )]));
    }
    if nodes.is_empty() {
        return Err(EmitError::Refused(vec![
            "no nodes to export; a sing-box config with no proxy outbound has nothing to \
             proxy through"
                .to_owned(),
        ]));
    }

    let tags =
        crate::translate::util::unique_tags(nodes, &[DIRECT_TAG, SELECTOR_TAG], FALLBACK_TAG);
    let label = nodes.len() > 1;

    let mut dropped = Vec::new();
    let mut refusals = Vec::new();
    let mut outbounds = Vec::with_capacity(nodes.len() + 2);
    let mut usable_tags = Vec::new();

    for (node, tag) in nodes.iter().zip(&tags) {
        // Collect every node's reasons rather than stopping at the first: a
        // user fixing a ten-node export should see all ten problems at once.
        let mut node_dropped = match gate(node, target, enhanced) {
            Ok(f) => f,
            Err(EmitError::Refused(reasons)) => {
                refusals.extend(reasons.iter().map(|r| prefix(r, tag, label)));
                continue;
            }
            Err(other) => return Err(other),
        };
        match proxy_outbound(node, target, tag, enhanced, &mut node_dropped) {
            Ok(o) => {
                outbounds.push(o);
                usable_tags.push(tag.clone());
                dropped.extend(node_dropped.into_iter().map(|d| Dropped {
                    field: d.field,
                    reason: prefix(&d.reason, tag, label),
                }));
            }
            Err(EmitError::Refused(reasons)) => {
                refusals.extend(reasons.iter().map(|r| prefix(r, tag, label)));
            }
            Err(other) => return Err(other),
        }
    }

    if usable_tags.is_empty() {
        return Err(EmitError::Refused(refusals));
    }

    // A node that failed while others succeeded is reported rather than
    // silently missing from the user's client.
    dropped.extend(refusals.into_iter().map(|r| Dropped::new("node", r)));

    let mut members: Vec<Value> = usable_tags.iter().map(|t| Value::String(t.clone())).collect();
    members.push(Value::String(DIRECT_TAG.to_owned()));

    outbounds.push(json!({
        "type": "selector",
        "tag": SELECTOR_TAG,
        "outbounds": members,
        "default": usable_tags[0].clone(),
    }));
    outbounds.push(json!({ "type": "direct", "tag": DIRECT_TAG }));

    let config = json!({
        "log": { "level": "info", "timestamp": true },
        // AdGuard DNS over HTTPS as the default resolver. Prevents local
        // DNS leaks; sing-box resolves DoH natively via type "https".
        "dns": {
            // Plain-IP fallbacks let sing-box resolve the DoH hostname itself.
            "servers": [
                { "tag": "adguard", "type": "https", "server": "https://dns.adguard-dns.com/dns-query" },
                { "tag": "adguard-fallback-1", "type": "udp", "server": "94.140.14.14" },
                { "tag": "adguard-fallback-2", "type": "udp", "server": "94.140.15.15" }
            ]
        },
        "inbounds": [ {
            "type": "mixed",
            "tag": "mixed-in",
            "listen": LISTEN_ADDRESS,
            "listen_port": LISTEN_PORT,
        } ],
        "outbounds": outbounds,
        "route": route_block(SELECTOR_TAG),
    });

    match serde_json::to_string_pretty(&config) {
        Ok(config) => Ok(Emitted { config, format: Format::Json, dropped }),
        Err(e) => Err(EmitError::Serialisation(e.to_string())),
    }
}

/// Attach a node's tag to a message, but only when there is more than one node
/// to tell apart.
fn prefix(reason: &str, tag: &str, label: bool) -> String {
    if label {
        format!("{tag}: {reason}")
    } else {
        reason.to_owned()
    }
}

